/** Timestamps are generated relative to "now" so the demo always looks
 *  freshly used, whatever day the presentation happens on. */
const ago = (days: number, hours = 0, minutes = 0) => {
  const d = new Date()
  d.setDate(d.getDate() - days)
  if (days > 0) d.setHours(hours, minutes, 0, 0)
  else d.setHours(d.getHours() - hours, d.getMinutes() - minutes, 0, 0)
  return d.toISOString()
}

